import type { DrawingKind } from '../lib/drawings';

/**
 * Места под фотографии.
 *
 * Каждая запись — это готовое место на странице: размеры, подпись, описание
 * для читающих с экрана и чертёж, который стоит там, пока фотографии нет.
 * Чтобы фотография появилась на сайте, её достаточно положить в
 * `src/assets/foto/` под именем ключа: `hero.jpg`, `obekt-vdnh.jpg` и так
 * далее. Ничего править в коде при этом не нужно — компонент подхватит файл
 * на сборке, сожмёт, отдаст AVIF и WebP и проставит ширину с высотой.
 *
 * Пока снимка нет, на месте стоит нарисованная сцена (`src/lib/scenes.ts`),
 * а если сцены для места не заведено — инженерный лист.
 *
 * Честность описаний. Сцены нарисованы, а не сняты, и на карточках объектов
 * показывают тип объекта, а не сам объект. Поэтому все `alt` начинаются
 * со слова «иллюстрация»: выдавать рисунок за снимок конкретного здания
 * нельзя, это ровно та подмена, которую запрещает раздел 5.6 ТЗ.
 * Появится настоящий снимок — компонент возьмёт его, а описание нужно будет
 * поправить здесь же.
 */

export type Photo = {
  /** Что должно быть на снимке. Это же попадёт в подсказку владельцу. */
  brief: string;
  /** Описание для читающих с экрана. Пишется под фотографию. */
  alt: string;
  /** Описание чертежа-заместителя. Пустая строка — чертёж декоративный. */
  fallbackAlt: string;
  /** Подпись под изображением. */
  caption?: string;
  /** Пропорции места: ширина к высоте. */
  ratio: [number, number];
  /** Доля ширины экрана, которую занимает место. Нужна для srcset. */
  sizes: string;
  /** Чертёж, который стоит здесь, пока фотографии нет. */
  fallback: DrawingKind;
};

