/** «от 750 ₽», «750–1 200 ₽» — единый формат цены по всему сайту. */
export function fmt(n: number): string {
  return n.toLocaleString('ru-RU').replace(/ /g, ' ');
}

export function priceLabel(p: PriceRow): string {
  if (p.from === 0) return 'бесплатно';
  return p.to ? `${fmt(p.from)}–${fmt(p.to)} ₽` : `от ${fmt(p.from)} ₽`;
}
